"""
ScamTrace — Page 7: Forensic Reports
Generates downloadable PDF investigation reports.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import streamlit as st
import pandas as pd
from datetime import datetime
import config
from modules.database import DatabaseManager
from modules.fraud_detection import FraudDetector, RISK_DISCLAIMER
from modules.evidence import EvidenceManager
from modules.reports import generate_pdf_report
from modules.graph_analytics import TransactionGraph

st.set_page_config(page_title="Forensic Reports — SCAMTRACE", layout="wide", page_icon="📋")

css_path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'assets', 'style.css')
if os.path.exists(css_path):
    with open(css_path) as f:
        st.markdown(f"<style>{f.read()}</style>", unsafe_allow_html=True)

@st.cache_resource
def get_db():
    db = DatabaseManager()
    if not db.is_data_loaded():
        db.load_synthetic_data()
    return db

db  = get_db()
em  = EvidenceManager(db_manager=db)

st.markdown("## 📋 Forensic Reports")
st.markdown(
    f"<div style='background:#1a1a2e;border:1px solid #d29922;border-radius:6px;"
    f"padding:8px 12px;font-size:11px;color:#d29922;margin-bottom:8px;'>"
    f"{config.SYNTHETIC_DATA_DISCLAIMER}</div>",
    unsafe_allow_html=True,
)
st.markdown(
    "<div style='background:#1a1a2e;border:1px solid #21262d;border-radius:6px;"
    "padding:8px 12px;font-size:11px;color:#8b949e;margin-bottom:16px;'>"
    "This report is generated from synthetic data for demonstration purposes. "
    "It does not represent real financial records or establish criminality.</div>",
    unsafe_allow_html=True,
)

tx_df  = db.get_transactions()
acc_df = db.get_accounts()
cmp_df = db.get_complaints()

if tx_df.empty:
    st.warning("No data loaded. Load demo data from Overview page.")
    st.stop()

tx_df['timestamp'] = pd.to_datetime(tx_df['timestamp'])

# ─── Report Configuration ───
st.markdown("### ⚙️ Report Configuration")
rc1, rc2 = st.columns(2)
with rc1:
    auto_case = f"CASE-{datetime.now().strftime('%Y%m%d-%H%M%S')}"
    case_id   = st.text_input("Case ID", value=auto_case)
    investigator = st.text_input("Investigator Name", value="Cyber Crime Unit Investigator")
with rc2:
    cmp_options  = cmp_df['complaint_id'].tolist() if not cmp_df.empty else []
    sel_cmps     = st.multiselect("Include Complaints", cmp_options, default=cmp_options)
    notes        = st.text_area("Case Notes", value="Synthetic demonstration report generated by ScamTrace.", height=80)

st.markdown("#### Sections to Include")
sc1, sc2, sc3 = st.columns(3)
with sc1:
    inc_evidence = st.checkbox("Evidence Inventory",     value=True)
    inc_tx_sum   = st.checkbox("Transaction Summary",    value=True)
with sc2:
    inc_sus      = st.checkbox("Suspicious Accounts",    value=True)
    inc_trails   = st.checkbox("Money Trail Details",    value=True)
with sc3:
    inc_risk     = st.checkbox("Risk Explanations",      value=True)
    inc_logs     = st.checkbox("Processing Logs",        value=True)

st.markdown("---")

# ─── Report Preview ───
with st.expander("👁️ Report Preview", expanded=False):
    st.markdown(f"**Case ID:** `{case_id}`  |  **Investigator:** {investigator}  |  **Date:** {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    st.markdown(f"**Complaints Covered:** {', '.join(sel_cmps) if sel_cmps else 'All'}")

    if inc_tx_sum and not tx_df.empty:
        st.markdown("**Transaction Summary:**")
        col_p1, col_p2, col_p3 = st.columns(3)
        with col_p1: st.metric("Total Tx", len(tx_df))
        with col_p2: st.metric("Total Amount", f"₹{tx_df['amount'].sum():,.0f}")
        with col_p3:
            flagged = int(tx_df['complaint_id'].notna().sum())
            st.metric("Flagged", flagged)

    if inc_sus and not acc_df.empty:
        st.markdown("**Accounts Summary (Mule IDs):**")
        mule_ids = [f'ACC_M{i:03d}' for i in range(1, 11)]
        mule_df  = acc_df[acc_df['account_id'].isin(mule_ids)]
        st.dataframe(mule_df[['account_id','account_holder','bank_name','risk_status']].head(5),
                     use_container_width=True, hide_index=True)

# ─── Generate Report ───
gen_col, _ = st.columns([1, 2])
with gen_col:
    gen_btn = st.button("📄 Generate Forensic Report PDF", type="primary", use_container_width=True)

if gen_btn:
    with st.spinner("Compiling evidence and generating PDF report…"):

        # Gather money trails
        money_trails = []
        tg = TransactionGraph(tx_df, acc_df)
        for cid in (sel_cmps if sel_cmps else cmp_df['complaint_id'].tolist()):
            cmp_row = cmp_df[cmp_df['complaint_id'] == cid]
            if not cmp_row.empty:
                orig = cmp_row.iloc[0]['originating_account']
                paths = tg.trace_money_trail(orig, max_depth=5)
                money_trails.extend(paths[:3])

        # Risk scores
        detector    = FraudDetector()
        features    = detector.compute_account_features(tx_df, acc_df)
        risk_scores = detector.compute_risk_scores(features)
        suspicious  = risk_scores[risk_scores['risk_score'] >= 50].to_dict('records')

        # Evidence records
        ev_records = em.get_evidence_records() if inc_evidence else []

        # TX summary
        complaint_txs = tx_df[tx_df['complaint_id'].isin(sel_cmps)] if sel_cmps else tx_df
        tx_summary = {
            'total': len(tx_df),
            'total_amount': float(tx_df['amount'].sum()),
            'date_from': str(tx_df['timestamp'].min())[:10],
            'date_to':   str(tx_df['timestamp'].max())[:10],
            'flagged': int(tx_df['complaint_id'].notna().sum()),
            'unique_accounts': int(pd.concat([tx_df['sender_account'], tx_df['receiver_account']]).nunique()),
        }

        # Logs
        logs_df  = db.get_investigation_logs(limit=20)
        log_list = logs_df['details'].tolist() if not logs_df.empty else []

        case_data = {
            'case_id':              case_id,
            'investigator':         investigator,
            'date':                 datetime.now().strftime('%Y-%m-%d %H:%M:%S'),
            'notes':                notes,
            'evidence_hashes':      ev_records   if inc_evidence else [],
            'transactions_summary': tx_summary   if inc_tx_sum   else {},
            'suspicious_accounts':  suspicious   if inc_sus       else [],
            'money_trails':         money_trails if inc_trails    else [],
            'risk_explanations':    suspicious   if inc_risk      else [],
            'processing_logs':      log_list     if inc_logs      else [],
        }

        try:
            pdf_bytes = generate_pdf_report(case_data)
            fname     = f"ScamTrace_{case_id}.pdf"

            st.success(f"✅ Report generated: `{fname}`")
            st.download_button(
                label="⬇️ Download Forensic Report PDF",
                data=pdf_bytes,
                file_name=fname,
                mime="application/pdf",
                use_container_width=True,
            )

            # Save to reports_output
            reports_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'reports_output')
            os.makedirs(reports_dir, exist_ok=True)
            with open(os.path.join(reports_dir, fname), 'wb') as f:
                f.write(pdf_bytes)

            db.log_investigation("REPORT_GENERATED",
                f"Case {case_id} | Investigator: {investigator} | {len(suspicious)} suspicious accounts | "
                f"{len(money_trails)} trails | Sections: evidence={inc_evidence}, trails={inc_trails}")

        except Exception as e:
            st.error(f"❌ Report generation failed: {e}")
            st.exception(e)

# ─── Previous Reports ───
st.markdown("---")
st.markdown("### 📁 Previously Generated Reports")
reports_dir = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'reports_output')
if os.path.exists(reports_dir):
    report_files = [f for f in os.listdir(reports_dir) if f.endswith('.pdf')]
    if report_files:
        for rf in sorted(report_files, reverse=True)[:10]:
            rpath = os.path.join(reports_dir, rf)
            size  = os.path.getsize(rpath)
            mtime = datetime.fromtimestamp(os.path.getmtime(rpath)).strftime('%Y-%m-%d %H:%M')
            with open(rpath, 'rb') as f:
                rb = f.read()
            st.markdown(f"""
            <div style="background:#161b22;border:1px solid #21262d;border-radius:6px;
                 padding:10px 14px;margin-bottom:6px;display:flex;align-items:center;justify-content:space-between;">
              <div>
                <span style="color:#e6edf3;font-weight:600;">{rf}</span>
                <span style="color:#8b949e;font-size:11px;margin-left:12px;">{mtime} &nbsp;|&nbsp; {size/1024:.1f} KB</span>
              </div>
            </div>""", unsafe_allow_html=True)
            st.download_button(f"⬇️ {rf}", data=rb, file_name=rf, mime="application/pdf",
                               key=f"dl_{rf}")
    else:
        st.info("No reports generated yet. Use the form above to create your first report.")
else:
    st.info("Reports directory not found.")

# ─── Logs ───
with st.expander("📜 Report Generation Logs"):
    logs_df = db.get_investigation_logs(limit=20)
    if not logs_df.empty:
        rpt_logs = logs_df[logs_df['action'].str.contains('REPORT', na=False)]
        if not rpt_logs.empty:
            st.dataframe(rpt_logs[['timestamp','action','details']], use_container_width=True, hide_index=True)
        else:
            st.info("No report generation logs yet.")
